def fetch(cp):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, "%x.png" % cp)
    if not os.path.exists(path):
        try:
            data = urllib.request.urlopen(URL % ("%x" % cp), timeout=20).read()
        except Exception:
            return None
        open(path, "wb").write(data)
    return Image.open(path).convert("RGBA")


def main():
    seen = []
    images = []
    for cp in CODEPOINTS:
        if cp in seen:
            continue
        im = fetch(cp)
        if im is None:
            print("no twemoji for %x" % cp)
            continue
        seen.append(cp)
        images.append(im)
    os.makedirs(OUT, exist_ok=True)
    rows = (len(images) + COLS - 1) // COLS
    for size, bgs in ((16, "wobt"), (40, "c")):
        for bg in bgs:
            c = BACKGROUNDS[bg]
            sheet = Image.new("RGB", (COLS * size, rows * size),
                              ((c >> 16) & 255, (c >> 8) & 255, c & 255))
            for i, im in enumerate(images):
                small = im.resize((size, size), Image.LANCZOS)
                sheet.paste(small, ((i % COLS) * size, (i // COLS) * size), small)
            sheet = sheet.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
            sheet.save(os.path.join(OUT, "emoji%d_%s.png" % (size, bg)), optimize=True)
    with open(os.path.join(OUT, "emoji.txt"), "w") as f:
        f.write("\n".join("%x" % cp for cp in seen) + "\n")
    print("%d emoji, %d columns" % (len(seen), COLS))


if __name__ == "__main__":
    main()
