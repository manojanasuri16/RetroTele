#!/bin/sh
# Generates bench/gen/h264bench_clips.h for tgh264bench.exe: x264 clips shaped like the
# official Telegram app's video (High profile, CABAC/CAVLC, 8x8 transform, no B-frames,
# 15 fps, low bitrate), pre-split into access units, with the FNV-1a sum of every decoded
# picture from the host build (the phone compares its output against them).
# Needs ffmpeg, x264, python3 and a C compiler. The output is git-ignored.
set -e
H=$(cd "$(dirname "$0")/.." && pwd)
G="$H/bench/gen"; mkdir -p "$G"
W=${OUT:-${TMPDIR:-/tmp}/h264dec_clips}; mkdir -p "$W"
OUT="$W/host" sh "$H/host_build.sh" >/dev/null
T="$W/host/h264dec_test"
# clip NAME SIZE SECONDS X264-OPTIONS...  (moving test picture + light noise, like a camera)
clip() {
  n=$1; s=$2; t=$3; shift 3
  ffmpeg -v error -f lavfi -i "testsrc2=s=1280x1280:rate=15,crop=$(echo $s | tr x :):'(iw-ow)/2+200*sin(t)':'(ih-oh)/2+150*cos(t*0.7)',noise=alls=6:allf=t" \
    -t "$t" -pix_fmt yuv420p -f yuv4mpegpipe - |
    x264 --quiet --demuxer y4m --fps 15 --bframes 0 --profile high --8x8dct --level 3.1 "$@" -o "$W/$n.264" - 2>/dev/null
  "$T" "$W/$n.264" /dev/null -max 528 960 -sums "$W/$n.sums" 2>/dev/null
}
clip cabac_176x320 176x320 4 --bitrate 150 --vbv-maxrate 150 --vbv-bufsize 150 --keyint 30 --ref 1
clip cavlc_176x320 176x320 2 --bitrate 150 --vbv-maxrate 150 --vbv-bufsize 150 --keyint 30 --ref 1 --no-cabac
clip cabac_240x480 240x480 2 --bitrate 200 --vbv-maxrate 200 --vbv-bufsize 200 --keyint 30 --ref 2
clip cabac_352x640 352x640 2 --bitrate 300 --vbv-maxrate 300 --vbv-bufsize 300 --keyint 30 --ref 2
python3 - "$W" "$G/h264bench_clips.h" cabac_176x320 cavlc_176x320 cabac_240x480 cabac_352x640 <<'EOF'
import sys
w, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
o = open(out, "w")
o.write("/* generated by tests/make_bench_clips.sh - do not edit */\n")
o.write("struct BenchClip { const char *name; const unsigned char *data; int len; const int *au; int naus;\n"
        "                   const unsigned int *sums; int nframes; int w, h; };\n")
for n in names:
    data = open("%s/%s.264" % (w, n), "rb").read()
    aus, sums, wh = [], [], (0, 0)
    for line in open("%s/%s.sums" % (w, n)):
        f = line.split()
        if f[0] == "au":
            aus.append((int(f[1]), int(f[2])))
        elif f[0] == "frame":
            sums.append(int(f[1], 16)); wh = (int(f[2]), int(f[3]))
    o.write("static const unsigned char clip_%s_data[%d] = {\n" % (n, len(data)))
    for i in range(0, len(data), 24):
        o.write(",".join(["%d" % c for c in data[i:i + 24]]) + ",\n")
    o.write("};\nstatic const int clip_%s_au[%d] = {\n" % (n, 2 * len(aus)))
    o.write(",\n".join(["%d,%d" % a for a in aus]) + "\n};\n")
    o.write("static const unsigned int clip_%s_sums[%d] = {\n" % (n, len(sums)))
    o.write(",\n".join(["0x%08xu" % v for v in sums]) + "\n};\n")
    sys.stderr.write("%s: %d bytes, %d access units, %d frames %dx%d\n" % (n, len(data), len(aus), len(sums), wh[0], wh[1]))
o.write("static const BenchClip kClips[] = {\n")
for n in names:
    wh = None
    for line in open("%s/%s.sums" % (w, n)):
        f = line.split()
        if f[0] == "frame":
            wh = (f[2], f[3])
    o.write('    { "%s", clip_%s_data, (int)sizeof(clip_%s_data), clip_%s_au, (int)(sizeof(clip_%s_au) / sizeof(int) / 2),\n'
            '      clip_%s_sums, (int)(sizeof(clip_%s_sums) / sizeof(unsigned int)), %s, %s },\n' % ((n,) * 7 + wh))
o.write("};\n#define KNumClips %d\n" % len(names))
o.close()
EOF
ls -la "$G/h264bench_clips.h"
